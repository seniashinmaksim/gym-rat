import { L } from '../i18n/core';

/**
 * Seed exercise library.
 *
 * Coefficients follow the fractional set model:
 *   1.0  = direct target muscle
 *   0.5  = significant secondary contributor
 *   0.25 = minor contributor
 *   0    = insignificant (omitted)
 * These are PRACTICAL ESTIMATES, not measured activation or hypertrophic stimulus.
 * They can be overridden per exercise in the app; all historical volume is
 * recomputed from raw sets, so overrides apply retroactively.
 */

type C = Partial<Record<MuscleId, number>>;
type R = Partial<Record<RegionId, number>>;

function ex(
  id: string,
  en: string,
  ru: string,
  aliases: string[],
  pattern: MovementPattern,
  category: 'compound' | 'isolation',
  equipmentKind: EquipmentKind,
  contributions: C,
  repRange: [number, number],
  defaultRestSec: number,
  biomechanicsEn: string,
  biomechanicsRu: string,
  extra: { regionEmphasis?: R; angleSensitive?: boolean } = {},
): ExerciseDef {
  // The note follows the language at the moment it is read (a getter, not a value frozen while the module loads).
  return { id, name: { en, ru }, aliases, pattern, category, equipmentKind, contributions, repRange, defaultRestSec, get biomechanics() { return L(biomechanicsEn, biomechanicsRu); }, ...extra };
}

